export function pickGreeting(now = new Date()): string {
  const h = now.getHours();
  const slot = GREETINGS.find((g) => g.hours.includes(h)) ?? GREETINGS[0];
  return slot.lines[Math.floor(Math.random() * slot.lines.length)];
}
