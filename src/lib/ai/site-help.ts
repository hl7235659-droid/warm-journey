// 关键词匹配打分：关键词命中 +1；标题包含查询片段再加权。返回 topN。
export function matchSiteHelp(query: string, topN = 3): HelpEntry[] {
  const q = (query || '').trim().toLowerCase();
  if (!q) return [];
  const scored = SITE_HELP
    .map((e) => {
      let score = 0;
      for (const kw of e.keywords) {
        if (q.includes(kw.toLowerCase())) score += 1;
      }
      const title = e.title.toLowerCase();
      if (q.length >= 2 && title.includes(q)) score += 2;
      return { entry: e, score };
    })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, topN).map((s) => s.entry);
}
